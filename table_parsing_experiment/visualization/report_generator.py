"""
Comprehensive Report Generator
종합 분석 리포트 HTML/PDF 생성
"""
from pathlib import Path
from typing import Dict, Any, List
import json
from datetime import datetime


class ReportGenerator:
    """종합 분석 리포트 생성기"""
    
    def __init__(self, experiment_dir: str):
        """
        Args:
            experiment_dir: 실험 결과 디렉토리
        """
        self.experiment_dir = Path(experiment_dir)
        self.results_file = self.experiment_dir / 'all_results.json'
        self.summary_file = self.experiment_dir / 'summary_statistics.json'
        
        # 데이터 로드
        self.all_results = self._load_json(self.results_file)
        self.summary_stats = self._load_json(self.summary_file)
    
    def _load_json(self, file_path: Path) -> Dict:
        """JSON 파일 로드"""
        if file_path.exists():
            with open(file_path, 'r', encoding='utf-8') as f:
                return json.load(f)
        return {}
    
    def generate_html_report(self, output_path: str):
        """HTML 리포트 생성"""
        html = self._generate_html_content()
        
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(html)
        
        print(f"Generated HTML report: {output_path}")
    
    def _generate_html_content(self) -> str:
        """HTML 콘텐츠 생성"""
        experiment_id = self.all_results[0].get('experiment_id', 'Unknown') if self.all_results else 'Unknown'
        
        html = f"""
<!DOCTYPE html>
<html lang="ko">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Table Parsing Experiment Report - {experiment_id}</title>
    <style>
        body {{
            font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif;
            margin: 0;
            padding: 20px;
            background-color: #f5f5f5;
        }}
        .container {{
            max-width: 1200px;
            margin: 0 auto;
            background-color: white;
            padding: 30px;
            box-shadow: 0 0 10px rgba(0,0,0,0.1);
        }}
        h1 {{
            color: #2c3e50;
            border-bottom: 3px solid #3498db;
            padding-bottom: 10px;
        }}
        h2 {{
            color: #34495e;
            margin-top: 30px;
            border-left: 4px solid #3498db;
            padding-left: 10px;
        }}
        table {{
            width: 100%;
            border-collapse: collapse;
            margin: 20px 0;
        }}
        th, td {{
            padding: 12px;
            text-align: left;
            border-bottom: 1px solid #ddd;
        }}
        th {{
            background-color: #3498db;
            color: white;
        }}
        tr:hover {{
            background-color: #f5f5f5;
        }}
        .metric-box {{
            display: inline-block;
            padding: 15px 25px;
            margin: 10px;
            background-color: #ecf0f1;
            border-radius: 5px;
            box-shadow: 0 2px 5px rgba(0,0,0,0.1);
        }}
        .metric-label {{
            font-size: 14px;
            color: #7f8c8d;
        }}
        .metric-value {{
            font-size: 24px;
            font-weight: bold;
            color: #2c3e50;
        }}
        .chart-container {{
            margin: 20px 0;
        }}
        .chart-image {{
            max-width: 100%;
            height: auto;
            border: 1px solid #ddd;
            border-radius: 5px;
        }}
        .error-type {{
            background-color: #e74c3c;
            color: white;
            padding: 2px 8px;
            border-radius: 3px;
            font-size: 12px;
        }}
        footer {{
            margin-top: 50px;
            padding-top: 20px;
            border-top: 1px solid #ddd;
            color: #7f8c8d;
            text-align: center;
        }}
    </style>
</head>
<body>
    <div class="container">
        <h1>📊 Table Parsing Experiment Report</h1>
        <p><strong>Experiment ID:</strong> {experiment_id}</p>
        <p><strong>Generated:</strong> {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}</p>
        
        <h2>📈 Overview</h2>
        {self._generate_overview_section()}
        
        <h2>🎯 Performance by Model</h2>
        {self._generate_model_performance_section()}
        
        <h2>📋 Performance by Table Type</h2>
        {self._generate_table_type_performance_section()}
        
        <h2>❌ Error Analysis</h2>
        {self._generate_error_analysis_section()}
        
        <h2>📊 Visualizations</h2>
        {self._generate_visualizations_section()}
        
        <footer>
            Generated by Table Parsing Experiment Framework
        </footer>
    </div>
</body>
</html>
"""
        return html
    
    def _generate_overview_section(self) -> str:
        """전체 개요 섹션"""
        total_samples = len(self.all_results)
        successful = sum(1 for r in self.all_results if r.get('parse_success', False))
        
        by_dataset = self.summary_stats.get('by_dataset', {})
        num_datasets = len(by_dataset)
        
        by_model = self.summary_stats.get('by_model', {})
        num_models = len(by_model)
        
        html = f"""
        <div class="metric-box">
            <div class="metric-label">Total Samples</div>
            <div class="metric-value">{total_samples}</div>
        </div>
        <div class="metric-box">
            <div class="metric-label">Successful Parses</div>
            <div class="metric-value">{successful}</div>
        </div>
        <div class="metric-box">
            <div class="metric-label">Datasets</div>
            <div class="metric-value">{num_datasets}</div>
        </div>
        <div class="metric-box">
            <div class="metric-label">Models</div>
            <div class="metric-value">{num_models}</div>
        </div>
        """
        return html
    
    def _generate_model_performance_section(self) -> str:
        """모델별 성능 섹션"""
        by_model = self.summary_stats.get('by_model', {})
        
        if not by_model:
            return "<p>No model performance data available.</p>"
        
        html = "<table><thead><tr><th>Model</th><th>Samples</th><th>TEDS</th><th>S-TEDS</th><th>F1</th></tr></thead><tbody>"
        
        for model, data in by_model.items():
            count = data.get('count', 0)
            metrics = data.get('metrics_avg', {})
            teds = metrics.get('teds', 0)
            s_teds = metrics.get('s_teds', 0)
            f1 = metrics.get('td_f1', 0)
            
            html += f"""
            <tr>
                <td>{model}</td>
                <td>{count}</td>
                <td>{teds:.3f}</td>
                <td>{s_teds:.3f}</td>
                <td>{f1:.3f}</td>
            </tr>
            """
        
        html += "</tbody></table>"
        return html
    
    def _generate_table_type_performance_section(self) -> str:
        """표 유형별 성능 섹션"""
        by_table_type = self.summary_stats.get('by_table_type', {})
        
        if not by_table_type:
            return "<p>No table type data available.</p>"
        
        html = "<table><thead><tr><th>Table Type</th><th>Samples</th><th>TEDS</th><th>S-TEDS</th></tr></thead><tbody>"
        
        for table_type, data in by_table_type.items():
            count = data.get('count', 0)
            metrics = data.get('metrics_avg', {})
            teds = metrics.get('teds', 0)
            s_teds = metrics.get('s_teds', 0)
            
            html += f"""
            <tr>
                <td>{table_type}</td>
                <td>{count}</td>
                <td>{teds:.3f}</td>
                <td>{s_teds:.3f}</td>
            </tr>
            """
        
        html += "</tbody></table>"
        return html
    
    def _generate_error_analysis_section(self) -> str:
        """오류 분석 섹션"""
        by_table_type = self.summary_stats.get('by_table_type', {})
        
        html = "<table><thead><tr><th>Table Type</th><th>Top Errors</th></tr></thead><tbody>"
        
        for table_type, data in by_table_type.items():
            errors = data.get('errors', {})
            
            if not errors:
                continue
            
            # 상위 3개 오류
            top_errors = sorted(errors.items(), key=lambda x: x[1], reverse=True)[:3]
            error_html = ", ".join([f'<span class="error-type">{e[0]} ({e[1]})</span>' for e in top_errors])
            
            html += f"""
            <tr>
                <td>{table_type}</td>
                <td>{error_html}</td>
            </tr>
            """
        
        html += "</tbody></table>"
        return html
    
    def _generate_visualizations_section(self) -> str:
        """시각화 섹션"""
        viz_dir = self.experiment_dir / 'visualizations'
        
        if not viz_dir.exists():
            return "<p>No visualizations available.</p>"
        
        html = ""
        
        # 이미지 파일 찾기
        for img_file in viz_dir.glob('*.png'):
            html += f"""
            <div class="chart-container">
                <h3>{img_file.stem.replace('_', ' ').title()}</h3>
                <img src="visualizations/{img_file.name}" class="chart-image" alt="{img_file.stem}">
            </div>
            """
        
        return html if html else "<p>No visualizations generated.</p>"


def generate_report_from_experiment(experiment_dir: str):
    """실험 결과로부터 리포트 생성"""
    generator = ReportGenerator(experiment_dir)
    
    # HTML 리포트
    html_path = Path(experiment_dir) / 'report.html'
    generator.generate_html_report(str(html_path))
    
    return html_path
